"""Build CHANGELOG.md and each release's notes from the git tags and history.

Both are derived rather than written by hand because the commit history is the
one record that cannot drift from what actually shipped. The repository only
allows squash merges titled with the PR title, so each commit subject on main
is a PR title, and those titles already read as changelog lines. The changelog
and the release notes share this code so the two describe a release the same
way.

CHANGELOG.md is regenerated in the release PR, before the tag exists, so that
the tagged commit and the release zip already carry their own section. That is
what --next is for: it describes main as it stands as the coming release.

Usage:
    python scripts/changelog.py changelog --next v1.4.0 --output CHANGELOG.md
    python scripts/changelog.py changelog [--output CHANGELOG.md]
    python scripts/changelog.py notes v1.4.0
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path

REPO_URL = "https://github.com/Sarks0/binary-mcp"
CHANGELOG_FILE = "CHANGELOG.md"

# The tag shape release.yml triggers on (v*.*.*), plus an optional semver
# prerelease suffix. Any other tag is not a release and is ignored.
TAG_PATTERN = re.compile(r"^v(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?$")

# GitHub appends "(#N)" to the subject of a squash merge.
PR_SUFFIX = re.compile(r"\s*\(#(\d+)\)$")

# A conventional-commits breaking footer. "BREAKING CHANGE" carries a space, so
# it cannot match the single-token trailer shape below and has to be tested
# first; "BREAKING-CHANGE" is the spec's own synonym for it.
BREAKING_FOOTER = re.compile(r"^BREAKING(?:[ -]CHANGE)?:\s*")
# A git trailer is "Key: value". The space after the colon is required so that
# a wrapped footer line starting with a URL ("https://...") is not mistaken
# for one and cut off.
TRAILER = re.compile(r"^[A-Za-z][A-Za-z0-9-]*: ")

# Dependabot opens one PR per bump. Listed one by one they bury the changes a
# reader came for, so they collapse to a single line per release.
DEPENDABOT_AUTHOR = "dependabot[bot]"

HEADER = """# Changelog

<!-- Generated by scripts/changelog.py from the git tags and commit history.
Do not edit by hand. Regenerate it in the release PR with
`make changelog VERSION=vX.Y.Z`. -->
"""

# Field and record separators for parsing git log. Control characters cannot
# appear in a commit message, so they cannot be confused with its content.
FIELD = "\x1f"
RECORD = "\x1e"


@dataclass(frozen=True)
class Tag:
    name: str
    date: str
    sort_key: tuple
    # What git reads for this release. The tag itself, except for the coming
    # release, which has no tag yet and is read from a branch instead.
    ref: str = ""

    @property
    def rev(self) -> str:
        return self.ref or self.name

    @property
    def is_prerelease(self) -> bool:
        return "-" in self.name


@dataclass(frozen=True)
class Commit:
    sha: str
    author: str
    subject: str
    body: str
    files: tuple[str, ...] = field(default=())

    @property
    def writes_changelog(self) -> bool:
        """Whether this is the release PR that wrote a changelog section.

        That commit is release housekeeping, not a change to describe. It also
        cannot be listed consistently: when its section is generated, the
        squash commit it will become does not exist yet.
        """
        return CHANGELOG_FILE in self.files


def version_key(name: str) -> tuple | None:
    """Semver precedence as a sort key, or None for a non-release tag.

    A prerelease sorts below its own release (1.3.0-rc1 < 1.3.0), the opposite
    of plain string order, where the longer name would count as newer.
    """
    match = TAG_PATTERN.match(name)
    if not match:
        return None
    major, minor, patch, pre = match.groups()
    if pre is None:
        return (int(major), int(minor), int(patch), 1, ())
    # Digit runs compare as numbers even inside an identifier, so rc10 sorts
    # above rc9. Strict semver would compare "rc10" and "rc9" as text and put
    # rc10 first; this matches git's own version sort, which release.yml used
    # before this script, and what anyone tagging rc10 means by it.
    pieces = tuple(
        (0, int(piece), "") if piece.isdigit() else (1, 0, piece)
        for piece in re.findall(r"\d+|\D+", pre)
    )
    return (int(major), int(minor), int(patch), 0, pieces)


def git(repo: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", *args],
        cwd=repo,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout


def list_tags(repo: Path) -> list[Tag]:
    """Release tags, newest version first."""
    output = git(
        repo, "for-each-ref", "refs/tags", f"--format=%(refname:strip=2){FIELD}%(creatordate:short)"
    )
    tags = []
    for line in output.splitlines():
        name, date = line.split(FIELD)
        key = version_key(name)
        if key is not None:
            tags.append(Tag(name=name, date=date, sort_key=key))
    return sorted(tags, key=lambda tag: tag.sort_key, reverse=True)


def previous_tag(tags: list[Tag], current: Tag) -> Tag | None:
    """The release to describe `current`'s changes against.

    A full release spans from the last FULL release, not from its own release
    candidate, or the range would leave out everything the candidate brought
    in. And it walks down from the tag's own position in version order rather
    than taking the newest other tag, so a patch on an older line does not
    compare against a newer release and describe the range backwards.
    """
    below = [tag for tag in tags if tag.sort_key < current.sort_key]
    if not current.is_prerelease:
        below = [tag for tag in below if not tag.is_prerelease]
    return below[0] if below else None


def read_commits(repo: Path, tag: Tag, previous: Tag | None) -> list[Commit]:
    rev_range = f"{previous.rev}..{tag.rev}" if previous else tag.rev
    # The record separator leads each commit so the file list --name-only
    # prints after the message stays inside that commit's record.
    output = git(
        repo,
        "log",
        "--name-only",
        f"--format={RECORD}%H{FIELD}%an{FIELD}%s{FIELD}%b{FIELD}",
        rev_range,
    )
    commits = []
    for record in output.split(RECORD):
        if not record.strip():
            continue
        sha, author, subject, body, files = record.split(FIELD, 4)
        commits.append(
            Commit(
                sha=sha,
                author=author,
                subject=subject,
                body=body.strip("\n"),
                files=tuple(line for line in files.splitlines() if line),
            )
        )
    return commits


def breaking_changes(commits: list[Commit]) -> list[str]:
    """Breaking-change footers, in the order the commits list them.

    A breaking change is the one thing a reader must not miss, and a list of
    subjects buries it: the squash commit that removed 159 tool names had a
    title about consolidation.

    Only a line that BEGINS with the token counts. Mid-sentence in running
    prose it describes a break rather than declaring one, and matching it there
    yields clipped fragments. A footer continues over wrapped lines and ends at
    a blank line, the end of the commit, or the next trailer. Trailers are
    written with no blank line between them, so without that last rule a
    following Co-Authored-By would be swallowed into the bullet.
    """
    found: list[str] = []

    def flush(buffer: list[str]) -> None:
        text = " ".join(buffer).strip()
        if text and text not in found:
            found.append(text)
        buffer.clear()

    for commit in commits:
        buffer: list[str] = []
        in_footer = False
        for line in f"{commit.subject}\n\n{commit.body}".splitlines():
            line = line.rstrip()
            match = BREAKING_FOOTER.match(line)
            if match:
                flush(buffer)
                buffer.append(line[match.end() :])
                in_footer = True
            elif not line.strip() or TRAILER.match(line):
                flush(buffer)
                in_footer = False
            elif in_footer:
                buffer.append(line.strip())
        flush(buffer)
    return found


def commit_link(commit: Commit) -> str:
    """A link to the commit's PR, or to the commit itself if it has none."""
    match = PR_SUFFIX.search(commit.subject)
    if match:
        number = match.group(1)
        return f"[#{number}]({REPO_URL}/pull/{number})"
    return f"[{commit.sha[:7]}]({REPO_URL}/commit/{commit.sha})"


def change_line(commit: Commit) -> str:
    # The PR number is replaced by a link rather than left as "(#N)", because
    # GitHub only auto-links issue references in comments and release bodies,
    # not in a rendered Markdown file.
    subject = PR_SUFFIX.sub("", commit.subject)
    return f"- {subject} ({commit_link(commit)})"


def pr_number(commit: Commit) -> int:
    match = PR_SUFFIX.search(commit.subject)
    return int(match.group(1)) if match else sys.maxsize


def render_release(
    tag: Tag, previous: Tag | None, commits: list[Commit], heading: str
) -> list[str]:
    """The body describing one release, with its subsections at `heading` level."""
    lines: list[str] = []

    breaking = breaking_changes(commits)
    if breaking:
        lines += [f"{heading} Breaking changes", ""]
        lines += [f"- {entry}" for entry in breaking]
        lines += ["", "Read these before upgrading.", ""]

    listed = [commit for commit in commits if not commit.writes_changelog]
    changes = [commit for commit in listed if commit.author != DEPENDABOT_AUTHOR]
    bumps = sorted(
        (commit for commit in listed if commit.author == DEPENDABOT_AUTHOR), key=pr_number
    )
    lines += [f"{heading} Changes", ""]
    lines += [change_line(commit) for commit in changes]
    if bumps:
        links = ", ".join(commit_link(commit) for commit in bumps)
        lines.append(f"- Dependency updates from Dependabot: {links}")
    if not listed:
        lines.append(f"- No changes since {previous.name if previous else 'the start'}.")
    lines.append("")

    if previous:
        lines += [
            f"Full diff: [{previous.name}...{tag.name}]({REPO_URL}/compare/{previous.name}...{tag.name})",
            "",
        ]
    return lines


def find_tag(tags: list[Tag], name: str) -> Tag:
    for tag in tags:
        if tag.name == name:
            return tag
    if version_key(name) is None:
        raise ValueError(f"{name} is not a release tag (expected vMAJOR.MINOR.PATCH[-PRERELEASE])")
    raise ValueError(f"tag {name} does not exist in this repository")


def coming_release(repo: Path, tags: list[Tag], name: str, head: str) -> Tag:
    """The release being prepared: `head` described as if it were tagged `name`."""
    key = version_key(name)
    if key is None or "-" in name:
        raise ValueError(
            f"--next {name} is not a full release version (expected vMAJOR.MINOR.PATCH)"
        )
    if any(tag.name == name for tag in tags):
        raise ValueError(f"--next {name} is already tagged; run without --next to rebuild it")
    if tags and key < tags[0].sort_key:
        raise ValueError(f"--next {name} is below the newest release, {tags[0].name}")
    try:
        git(repo, "rev-parse", "--verify", "--quiet", f"{head}^{{commit}}")
    except RuntimeError:
        raise ValueError(f"--head {head} is not a commit in this repository") from None
    today = datetime.now(UTC).date().isoformat()
    return Tag(name=name, date=today, sort_key=key, ref=head)


def build_notes(repo: Path, name: str) -> str:
    tags = list_tags(repo)
    tag = find_tag(tags, name)
    previous = previous_tag(tags, tag)
    lines = render_release(tag, previous, read_commits(repo, tag, previous), heading="##")
    return "\n".join(lines)


def build_changelog(repo: Path, next_version: str | None = None, head: str = "origin/main") -> str:
    """Every full release, newest first, plus the coming one if `next_version` is set.

    Prereleases get no section of their own: a release candidate is a trial
    build, and everything it carried is listed under the full release that
    shipped it.
    """
    tags = list_tags(repo)
    if next_version:
        tags = [coming_release(repo, tags, next_version, head), *tags]
    lines = [HEADER]
    for tag in (tag for tag in tags if not tag.is_prerelease):
        previous = previous_tag(tags, tag)
        lines += [f"## {tag.name} - {tag.date}", ""]
        lines += render_release(tag, previous, read_commits(repo, tag, previous), heading="###")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", type=Path, default=Path.cwd(), help="git repository to read")
    commands = parser.add_subparsers(dest="command", required=True)

    changelog = commands.add_parser("changelog", help="build the whole CHANGELOG.md")
    changelog.add_argument("--output", type=Path, help="file to write instead of stdout")
    changelog.add_argument(
        "--next", dest="next_version", help="add a section for the release being prepared"
    )
    changelog.add_argument(
        "--head",
        default="origin/main",
        help="what the coming release contains (default: origin/main, i.e. main as merged)",
    )

    notes = commands.add_parser("notes", help="build one release's notes")
    notes.add_argument("tag", help="the release tag, e.g. v1.3.0")

    args = parser.parse_args(argv)
    try:
        if args.command == "changelog":
            text = build_changelog(args.repo, args.next_version, args.head)
        else:
            text = build_notes(args.repo, args.tag)
    except (RuntimeError, ValueError) as error:
        print(f"changelog: {error}", file=sys.stderr)
        return 1

    if args.command == "changelog" and args.output:
        args.output.write_text(text, encoding="utf-8", newline="\n")
    else:
        # PR titles are UTF-8, and a Windows console defaults to a narrower
        # code page that would fail on the first character outside it.
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
